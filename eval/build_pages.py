def ppl(x):
    return f"{x:,.0f}" if x >= 100 else f"{x:.1f}"


def ci(c, fmt=ppl):
    return f"{fmt(c[0])}–{fmt(c[1])}"


def pc(x, d=1):
    return f"{100 * x:.{d}f}%"


def mcq_verdict(m):
    lo, hi = m['ci95']
    if lo > 0.25 and m['accuracy'] < m['majorityClassBaseline']:
        return f"slightly above chance, but below always answering the most common letter ({pc(m['majorityClassBaseline'], 0)})"
    if lo > 0.25:
        return 'above chance'
    if hi < 0.25:
        return 'below chance'
    return 'not distinguishable from chance'


qa_ratio = C['sftVsPretrainedQaPerplexityRatio']
pm_ratio = C['sftVsPretrainedPubmedPerplexityRatio']
qa_change = 1 - qa_ratio['ratio']          # >0 means SFT lower perplexity
qa_sig = qa_ratio['ci95'][1] < 1
pm_change = pm_ratio['ratio'] - 1          # >0 means SFT higher perplexity on PubMed
pm_sig = pm_ratio['ci95'][0] > 1 or pm_ratio['ci95'][1] < 1
date = RES['generated'][:10]

def qa_sentence():
    if qa_sig and qa_change > 0:
        return (f"Medical SFT lowers held-out Q&amp;A perplexity by {pc(qa_change, 0)} "
                f"({ppl(PRE['medicalQaHeldOut']['perplexity'])} → {ppl(SFT['medicalQaHeldOut']['perplexity'])}; paired 95% CI of the ratio "
                f"{qa_ratio['ci95'][0]:.2f}–{qa_ratio['ci95'][1]:.2f}).")
    return (f"Held-out Q&amp;A perplexity: {ppl(PRE['medicalQaHeldOut']['perplexity'])} before SFT, {ppl(SFT['medicalQaHeldOut']['perplexity'])} after "
            f"(paired ratio CI {qa_ratio['ci95'][0]:.2f}–{qa_ratio['ci95'][1]:.2f}).")


def pm_sentence():
    a, b = PRE['pubmedHeldOut']['perplexity'], SFT['pubmedHeldOut']['perplexity']
    if pm_sig and pm_change > 0:
        return f"On PubMed text the pretrained checkpoint stays better ({ppl(a)} vs {ppl(b)}): SFT trades some general biomedical fit for the Q&amp;A format."
    if pm_sig and pm_change < 0:
        return f"SFT also improves PubMed perplexity ({ppl(a)} → {ppl(b)})."
    return f"PubMed perplexity is about the same before and after SFT ({ppl(a)} vs {ppl(b)})."


def routing_cells(rt):
    rows = []
    for li, layer in enumerate(rt):
        cells = ''.join(
            f'<span class="me-cell" style="--s:{s:.3f}" title="Layer {li + 1}, expert {e + 1}: {pc(s)} of selections">{round(100 * s)}</span>'
            for e, s in enumerate(layer['share']))
        rows.append(f'<div class="me-route-row"><span class="me-route-l">L{li + 1}</span>{cells}<span class="me-route-h">{layer["normalizedEntropy"]:.2f}</span></div>')
    return '\n'.join(rows)


def min_entropy(rt):
    return min(l['normalizedEntropy'] for l in rt)



def put_between(text, block, anchor_after):
    if '<!-- model-eval:start -->' in text:
        return re.sub(r'<!-- model-eval:start -->.*?<!-- model-eval:end -->', lambda m: block.strip(), text, flags=re.S)
    i = text.index(anchor_after)
    return text[:i] + block.strip() + '\n\n    ' + text[i:]


